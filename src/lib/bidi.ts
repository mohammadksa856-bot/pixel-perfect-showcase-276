/**
 * عزل اتجاه الأرقام والتواريخ داخل النص العربي (LRI…PDI) حتى لا تنعكس التواريخ
 * ولا تتبدل مواقع الإشارة السالبة. لا يغيّر القيمة؛ رموز غير مرئية فقط.
 */
export const iso = (s: string | number) => `⁦${s}⁩`;

/** يزيل رموز العزل؛ للمقارنة في الاختبارات أو النسخ النصي. */
export const stripIsolates = (s: string) => s.replace(/[⁦-⁩]/g, "");
